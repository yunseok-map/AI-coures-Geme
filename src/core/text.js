// 화면에 글을 넣을 때 쓰는 두 가지.
//
// 콘텐츠 파일(games/, data/)에서는 강조를 `**이렇게**` 로 적는다.
// 그대로 innerHTML 에 넣으면 별표가 그대로 보이므로 여기서 <b> 로 바꾼다.
// HTML 을 먼저 이스케이프한 뒤에 바꾸므로 콘텐츠가 태그를 주입할 수 없다.

export function esc(s) {
  return String(s == null ? '' : s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

/** `**강조**` → <b>강조</b>. 이스케이프가 먼저다. */
export function strong(s) {
  return esc(s).replace(/\*\*([^*]+)\*\*/g, '<b>$1</b>');
}

/**
 * 강조 표시만 떼고 글자만 남긴다. 낭독 영역(`#live`)에 쓴다.
 *
 * 낭독 영역은 textContent 라서 별표가 그대로 남는다. 눈으로는 안 보이지만
 * 스크린리더는 "별표별표 CLI 에이전트 별표별표" 로 읽는다 — 실제로 그렇게 되어 있었다.
 * 낭독에 강조 표시는 의미가 없으므로 떼고 넘긴다.
 */
export function plain(s) {
  return String(s == null ? '' : s).replace(/\*\*([^*]+)\*\*/g, '$1');
}

/**
 * 한 문단을 문장 단위로 끊는다.
 *
 * 사용자: 워크슬롭을 알려 줄 때 글이 아래로 내려가서 보기 어렵다고 했다.
 * 결과 화면의 “방금 한 것의 이름” 칸이 그랬다 — 14번은 **189자 한 문단에
 * 용어 네 개**, 15번은 225자였다. 폭이 좁으면 그게 세 줄로 감기고, 감긴 줄에는
 * 눈이 걸 자리가 없다. 어디까지가 워크슬롭 설명이고 어디부터 AI 슬롭인지
 * 글줄만 봐서는 안 갈린다.
 *
 * 글을 고쳐서 풀지 않는다 — 열네 판의 문장을 다시 쓰면 검증한 사실이 흔들린다.
 * 문장 경계에서 끊어 **한 줄에 한 문장**으로 세우기만 한다. 뜻은 그대로고
 * 용어마다 굵은 글씨가 줄머리 근처에 서서 눈이 걸 자리가 생긴다.
 *
 * 끊는 자리는 종결어미 뒤 공백뿐이다(`…다.` `…한다.`). 문장 안의 마침표
 * (“3.5” 같은 것)에서 끊기지 않게 **앞이 숫자가 아닐 때만** 끊는다.
 * `**강조**` 는 건드리지 않는다 — 자른 뒤 각 줄을 `strong()` 에 넣는다.
 *
 * 마침표 뒤에 닫는 따옴표가 오는 경우(`…모델이다.”`)와 앞이 영문인 경우
 * (`… + Harness.`)도 문장 끝이다. 이 둘을 빼 두었더니 6번과 13번에서
 * 두 문장이 붙은 채 96자·80자 한 줄로 남았다. `AGENTS.md` 처럼 마침표 뒤에
 * 공백이 없는 것은 애초에 걸리지 않는다.
 *
 * @param {string} s 문단
 * @returns {string[]} 문장들. 빈 문단이면 빈 배열
 */
export function sentences(s) {
  const t = String(s == null ? '' : s).trim();
  if (!t) return [];
  return t
    // `*` 도 넣는다 — `**컨텍스트 로트**.` 처럼 굵은 낱말로 끝나는 문장이 있다
    .split(/(?<=[가-힣a-zA-Z*”"’')\]]\.["”’')\]]?)\s+/)
    .map(x => x.trim())
    .filter(Boolean);
}

/** 용어를 나열하는 자리 — 굵은 낱말 뒤에 붙는 쉼표. `**커맨드**, ` `**...팀**이고, ` */
const ENUM = /(?<=\*\*[^*]{1,24}\*\*[가-힣]{0,4},)\s+/;

/** 한 줄이 이보다 길면 감긴다. 감긴 줄에는 눈이 걸 자리가 없다 */
const LONG = 70;

/**
 * "방금 한 것의 이름" 칸을 **읽을 수 있는 줄들**로 끊는다.
 *
 * 두 번 끊는다.
 *  1) 문장 경계 — `sentences()`
 *  2) 그러고도 긴 **나열 문장**은 굵은 낱말 뒤 쉼표에서 한 번 더.
 *     8번이 "…것이 **커맨드**, …것이 **스킬**, …것이 **훅**, …" 하는 식으로
 *     **한 문장에 용어 다섯 개, 133자**였다. 다섯 도구를 가르는 판인데 다섯이
 *     한 덩어리로 붙어 있으면 무엇이 몇 개인지부터 안 보인다. 한 줄에 하나씩 세운다.
 *
 * 짧은 문장은 건드리지 않는다 — 쉼표마다 끊으면 도리어 잘게 부서진다.
 *
 * 자르는 자리는 **언제나 `**` 짝 바깥**이다. 그래도 콘텐츠가 어떻게 바뀔지 모르니
 * 자른 뒤 짝이 맞는지 세어 보고, 하나라도 어긋나면 통째로 되돌린다 —
 * 짝이 깨진 조각을 `strong()` 에 넣으면 별표가 화면에 그대로 나간다.
 *
 * @param {string} s 문단 (`**강조**` 표기 그대로)
 * @returns {string[]} 화면에 한 줄씩 세울 조각들
 */
export function termLines(s) {
  const out = [];
  for (const one of sentences(s)) {
    if (one.replace(/\*\*/g, '').length <= LONG) { out.push(one); continue; }
    const parts = one.split(ENUM).map(x => x.trim()).filter(Boolean);
    out.push(...(parts.length > 1 ? parts : [one]));
  }
  const even = out.every(x => (x.match(/\*\*/g) || []).length % 2 === 0);
  return even ? out : sentences(s);
}
