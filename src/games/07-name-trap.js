//   - 그래서 코딩과 무관한 파일 작업에도 쓰이고, 개발자가 아닌 사람을 위한 도구가 따로 나왔다
//   - Codex: 한 이름이 제품에도 모델 갈래에도 붙어 있다 (2026-08 공식 문서 확인)
//
// 난이도 — 사용자가 이 판을 두고 “문제가 어려울 것 같으니 수정해 달라”고 했다.
//
// 주석에 곧은 따옴표(")를 쓰지 않는다: 글꼴 조각 검사가 따옴표 안을 문자열로 보고
// 화면에 나가는 글자로 세어서, 주석에만 있는 음절 때문에 폰트를 다시 만들라고 한다.
// 여덟 문항 중 둘이 **카드만 봐서는 답할 방법이 없는 문항**이었다.
//   · 지침 파일(CLAUDE.md · AGENTS.md · GEMINI.md)이 같은 일을 하냐 — 이건 10번 판이
//     가르치는 내용이다. 여기서는 아직 안 배운 것을 미리 물어본 셈이라 찍기가 된다. 뺐다.
//   · Codex 가 모델과 같은 물건이냐 — 바깥 사실을 **알아야만** 답할 수 있으면 찍기가
//     된다. 그래서 갈리는 근거를 카드 안에 넣고 서로 부딪히게 했다:
//     "모델 목록에 있다"와 "동료가 설치해서 쓴다"가 한 카드에 있으면 같은 물건일 수 없다.
