  data: {
    ask: '이 일을 CLI 에이전트한테 시킬 수 있을까?',
    yes: '시킬 수 있다',
    no: '못 시킨다',
    runCaption: '실제로 시켜 본다',
    items: ITEMS
  },

  simulate(setup, d) {
    const items = (d && d.items) || ITEMS;
    const byId = new Map(items.map(i => [i.id, i]));
    const r = new Run();

    const bets = setup.bets || [];

    // 엔진은 문항마다 하나씩 걸어야 다음으로 넘어가므로 여기 걸릴 일은 없다.
    // 그래도 두는 이유: 이 판은 "건 것"이 없으면 판정할 것 자체가 없다.
    // 없는데 점수를 매기면 아무것도 안 하고 통과하는 길이 생긴다.
    if (!bets.length) {
      r.warn('건 것이 하나도 없다');
      r.fault('걸지 않았다', '이 판은 먼저 걸어야 시작된다', 100);
      r.out('건 기록 없음');
      return r.finish({ pass: 70, partial: 40 });
    }

    const wrong = bets.filter(b => byId.get(b.id) && byId.get(b.id).answer !== b.bet);
    const hits = bets.length - wrong.length;

    r.read(`걸었던 ${bets.length}건을 다시 펼친다`);

    // 이 판의 임팩트 모먼트 — 정답 개수가 아니라 **어느 쪽으로 기울었는지**를 보여 준다.
    const canBets = bets.filter(b => byId.get(b.id) && byId.get(b.id).axis === 'can');
    const saidNo = canBets.filter(b => b.bet === false).length;

    r.do(`“시킬 수 있나” 문항 ${canBets.length}건 중 ${saidNo}건을 “못 시킨다” 쪽에 걸었다`);
    r.read(`실제로 못 시키는 것은 ${CAN_NO}건이었다`);

    // 빗나간 건수도 센다. 편향만 보면 "고르게 틀린 사람"이 만점으로 끝난다.
    r.score -= 6 * wrong.length;

    if (saidNo > CAN_NO) {
      r.warn('할 수 있는 일을 못 한다고 걸었다 — 대부분 이름을 보고 판단한다');
      r.fault('이름이 만든 진입장벽',
        '“Code”가 붙었다는 이유로 자기 일이 아니라고 미리 접었다. 실제 기준은 파일을 다루는 일이냐다',
        12 * (saidNo - CAN_NO));
    } else if (saidNo < CAN_NO) {
      r.warn('못 하는 일까지 된다고 걸었다 — 범위를 넓게 봤다');
      r.fault('범위 착각',
        '내 컴퓨터의 파일과 명령까지가 이 도구의 범위다. 바깥 시스템은 통로를 따로 열어야 한다',
        12 * (CAN_NO - saidNo));
    } else {
      r.ok('할 수 있는 일과 없는 일을 정확히 갈랐다');
      r.gain('범위 감각', '이름이 아니라 다루는 대상으로 판단했다', 6);
    }

    for (const w of wrong) {
      const it = byId.get(w.id);
      r.read(`빗나감 — ${it.text.slice(0, 22)}…`);
    }
    if (!wrong.length) r.ok('여덟 건을 전부 맞혔다');

    r.out(hits >= 6
      ? `${bets.length}건 중 ${hits}건 적중 — 이름이 아니라 다루는 대상으로 봤다`
      : `${bets.length}건 중 ${hits}건 적중 — 빗나간 쪽에 공통점이 있다`);

    // 반려(fail) 로 떨어뜨리지 않는다 — 이 판은 맞히라고 만든 게 아니라
    // 자기가 어디로 기우는지 보라고 만들었다. 그 사람에게 용어를 안 주면
    // 정작 이 판이 겨냥한 사람만 빈손으로 나간다.
    return r.finish({ pass: 70, partial: 25 });
  },

