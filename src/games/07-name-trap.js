//   - 그래서 코딩과 무관한 파일 작업에도 쓰이고, 비개발자용 도구가 따로 나왔다
//   - Codex: 2021년 모델은 2023년 3월 폐기, 2025년 5월 같은 이름의 다른 제품
//   - 지침 파일: CLAUDE.md · AGENTS.md · GEMINI.md, 목적 같고 이름만 다르다

